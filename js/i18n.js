/* ===================================================================
   Bible Quizzy — bilingual UI layer (English / Spanish).

   Scope: this translates the app's CHROME — navigation, buttons, labels,
   toasts, book/group names and one-line tags. It does NOT translate quiz
   CONTENT (book/chapter overviews, questions, cast bios, hard words,
   underline verses, prayers, reflection prompts) — that stays in English
   for now and is a separate follow-up effort. A few sentences in the app
   splice a translated label next to untranslated content text (for
   example a book's one-line tag followed by its English overview); until
   content is translated those specific sentences will read as mixed
   English/Spanish. Everything else — every button, header, toast, round
   name, stat label, and all 66 book names — is fully bilingual.

   LANG is persisted in localStorage under "bq:lang". setLang() swaps the
   book/group name+tag+desc fields in place (BOOKS/GROUPS are shared
   objects referenced by app.js, so this takes effect everywhere without
   needing a page reload) and the caller is responsible for re-rendering
   the current screen afterward (see switchLang() in app.js).
   =================================================================== */
"use strict";

const I18N_KEY = "lang";

function detectLang() {
  try {
    const saved = localStorage.getItem("bq:" + I18N_KEY);
    if (saved === "en" || saved === "es") return saved;
  } catch (e) {}
  const nav = ((navigator.language || (navigator.languages && navigator.languages[0]) || "en") + "").toLowerCase();
  return nav.indexOf("es") === 0 ? "es" : "en";
}
let LANG = detectLang();

function applyBookLanguage() {
  (window.BQ_GROUPS || []).forEach((g) => {
    if (g.nameEn === undefined) { g.nameEn = g.name; g.descEn = g.desc; }
    g.name = (LANG === "es" && g.nameEs) || g.nameEn;
    g.desc = (LANG === "es" && g.descEs) || g.descEn;
  });
  (window.BQ_BOOKS || []).forEach((b) => {
    if (b.nameEn === undefined) { b.nameEn = b.name; b.tagEn = b.tag; }
    b.name = (LANG === "es" && b.nameEs) || b.nameEn;
    b.tag = (LANG === "es" && b.tagEs) || b.tagEn;
  });
}
applyBookLanguage();

function setLang(l) {
  LANG = l === "es" ? "es" : "en";
  try { localStorage.setItem("bq:" + I18N_KEY, LANG); } catch (e) {}
  document.documentElement.lang = LANG;
  applyBookLanguage();
}
